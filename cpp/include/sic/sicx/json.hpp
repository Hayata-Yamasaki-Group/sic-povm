// sic-fiducial-json/1.0 per-ray documents ray-NN.json, the release catalogue,
// and the optional all-in-one export (docs/sicx.md sections 9 and 10;
// docs/sicx.md section 9; schemas in docs/schemas/). Every number is a string.
// Levels per ray:
//   fp32, fp64: IEEE-754 bit patterns (hex) and round-trip decimals, each
//         certified to be the correct rounding (nearest, ties to even) of the
//         exact normalized, gauged coordinate (fp32 is never rounded from fp64);
//         error_bound is a power of two above every |value - exact|.
//   hp:   decimal balls [mid_re, rad_re, mid_im, rad_im] with a fixed number
//         of decimal places; each contains the BALL record of the SICX file
//         (outward rounding), so it contains the exact coordinate.
// exact.json (power basis) is not generated by this version.
#pragma once

#include <cmath>
#include <cstring>
#include <fstream>

#include "sic/sicx/io.hpp"

namespace sic::sicx {

// Correct rounding of an exactly known ball to binary64: both endpoints must
// round to the same double; otherwise the ball is too wide and this fails.
double certified_round(const arb_t x, const std::string& what);

std::string double_hex(double value);
std::string double_decimal17(double value);

// Decimal with exactly `places` decimals of the integer n * 10^-places.
std::string fixed_decimal(const fmpz_t n, slong places);

// Outward decimal ball with `places` decimals: mid' = round(mid), rad' = ceil(rad * 10^p) + 1
// units, so [mid' +- rad'] contains [mid +- rad] (|mid - mid'| <= 1/2 unit).
struct DecimalBall {
  std::string midpoint;
  std::string radius;
};
DecimalBall decimal_ball(const arb_t x, slong places, arb_t radius_out);

// Correct rounding to binary32 (round to nearest, ties to even): both ends of
// the ball must round to the same normal (or zero) binary32 value.
float certified_round32(const arb_t x, const std::string& what);
std::string float_hex(float value);
std::string float_decimal9(float value);
// Power of two strictly above every |value - exact| (value from the rounding).
std::string error_bound_text(double max_error);

// The numerical levels of one ray: fp32, fp64 (each the certified correct
// rounding of the exact coordinate, from the BALL ball) and hp (outward decimal
// balls containing the BALL ball).
void ray_levels(const Reader& reader, size_t ri, sic::support::Json& x);

// Keep the canonical c<N> label validated in RAYS (numeric lexicographic word order).
std::string ray_class(const std::string& label);
void require_multiplet(const std::string& label);
std::string ray_full_id(const Meta& meta, size_t ri, const std::string& multiplet = "");
std::string ray_file_name(const Meta& meta, size_t ri);

// ray-NN.json (schema sic-fiducial-json/1.0, docs/sicx.md section 9).
sic::support::Json ray_json(const Reader& reader, size_t ri, const std::string& sicx_name,
                            const std::string& sicx_sha256, bool exact_present,
                            const std::string& multiplet = "");

// Optional all-in-one export for small d (not a release file): every ray document.
sic::support::Json all_in_one_json(const Reader& reader, const std::string& sicx_name,
                                   const std::string& sicx_sha256,
                                   const std::string& multiplet = "");

}  // namespace sic::sicx
