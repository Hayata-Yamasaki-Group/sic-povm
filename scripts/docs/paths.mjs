// Source and installed-header pointers are checked even inside shell templates.
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
export function checkPaths(root,text,file) {
  const generated=new Set([...text.matchAll(/<!-- generated-path: ([^ ]+) -->/g)].map(m=>m[1]));
  const used=new Set();
  for(const line of text.split('\n')) {
    if(line.trimStart().match(/^<!-- generated-path:/))continue;
    for(const m of line.matchAll(/(?<![A-Za-z0-9_./])((?:cpp|scripts|data|docs|references|include|tests)\/[A-Za-z0-9_./<>${}*?=-]+|sic\/[A-Za-z0-9_./-]+)/g)) {
      let name=m[1].replace(/[.]+$/,'');
      if(/[<>*$?{}=]/.test(name))continue; // Explicit parameterized spelling, not a concrete path.
      if(name.startsWith('cpp/build'))continue; // Build trees are generated by configure/build.
      if(generated.has(name)){used.add(name);continue;}
      if(name.startsWith('include/')||name.startsWith('tests/'))name='cpp/'+name;
      if(name.startsWith('sic/'))name='cpp/include/'+name;
      assert(fs.existsSync(path.join(root,name)),`paths: ${file}: missing ${name}`);
    }
  }
  for(const name of generated)assert(used.has(name),`paths: unused generated-path classification ${file}: ${name}`);
}
